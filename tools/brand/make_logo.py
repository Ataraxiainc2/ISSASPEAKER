"""Generate every ISSASPEAKER logo asset from one definition. Re-run after changing the shapes or colors.

    python tools/brand/make_logo.py

Writes the launcher foreground, background and monochrome layers, the in-app mark (ic_logo), and the
SVG pages under docs/play/ that are rendered to PNG for Google Play (see docs/play/README.md).

Concept: a smart speaker (the pill) with four status lights, one per family of services the app joins
(Google, AI, music, routines); sound waves on both sides end in nodes: the services it connects.
Coordinates use the 108-unit adaptive-icon grid; everything stays inside the 66-unit safe circle.
"""

import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
RES = ROOT / "app" / "src" / "main" / "res"
PLAY = ROOT / "docs" / "play"

BG_TOP, BG_BOTTOM = "#1B2550", "#0B1029"
BODY, BODY_SHADE, FABRIC = "#F4EFE6", "#E3DCCD", "#D3CABA"
CORAL, AMBER, TEAL, VIOLET = "#FF6B5A", "#FFC857", "#2EC4B6", "#8B7CF6"


def circle(cx, cy, r):
    return f"M{cx - r:.2f},{cy:.2f}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0z"


# (kind, path, color, stroke width); kind "fill" or "stroke".
SHAPES = [
    ("fill", "M44,44a10,10 0 0 1 20,0v24a10,10 0 0 1 -20,0z", BODY, 0),
    ("fill", "M54,34a10,10 0 0 1 10,10v24a10,10 0 0 1 -10,10z", BODY_SHADE, 0),
    *[("stroke", f"M47.5,{y}H60.5", FABRIC, 0.9) for y in (56, 60, 64, 68)],
    ("fill", circle(48.2, 46, 1.6), CORAL, 0),
    ("fill", circle(52.1, 46, 1.6), AMBER, 0),
    ("fill", circle(55.9, 46, 1.6), TEAL, 0),
    ("fill", circle(59.8, 46, 1.6), VIOLET, 0),
    ("stroke", "M67.93,46.25A17,17 0 0 1 67.93,65.75", AMBER, 3.2),
    ("stroke", "M40.07,46.25A17,17 0 0 0 40.07,65.75", AMBER, 3.2),
    ("stroke", "M73.66,42.23A24,24 0 0 1 73.66,69.77", TEAL, 3.2),
    ("stroke", "M34.34,42.23A24,24 0 0 0 34.34,69.77", TEAL, 3.2),
    ("fill", circle(73.66, 42.23, 2.6), CORAL, 0),
    ("fill", circle(73.66, 69.77, 2.6), VIOLET, 0),
    ("fill", circle(34.34, 42.23, 2.6), VIOLET, 0),
    ("fill", circle(34.34, 69.77, 2.6), CORAL, 0),
]

HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/brand/make_logo.py. Do not edit by hand. -->\n'


def vector_paths(color_override=None, skip_shade=False):
    out = []
    for kind, path, color, width in SHAPES:
        if skip_shade and color in (BODY_SHADE, FABRIC):
            continue
        c = color_override or color
        if kind == "fill":
            out.append(f'    <path android:fillColor="{c}" android:pathData="{path}" />')
        else:
            out.append(
                f'    <path android:pathData="{path}" android:strokeColor="{c}" '
                f'android:strokeWidth="{width}" android:strokeLineCap="round" />'
            )
    return "\n".join(out)


def vector(body, size=108, viewport=108, translate=0, extra_ns=""):
    group_open = f'    <group android:translateX="{-translate}" android:translateY="{-translate}">\n' if translate else ""
    group_close = "\n    </group>" if translate else ""
    return (
        f'{HEADER}<vector xmlns:android="http://schemas.android.com/apk/res/android"{extra_ns}\n'
        f'    android:width="{size}dp"\n    android:height="{size}dp"\n'
        f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n'
        f"{group_open}{body}{group_close}\n</vector>\n"
    )


def gradient_rect(path):
    return (
        f'    <path android:pathData="{path}">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient android:type="linear" android:startX="0" android:startY="0" '
        f'android:endX="108" android:endY="108" android:startColor="{BG_TOP}" android:endColor="{BG_BOTTOM}" />\n'
        "        </aapt:attr>\n    </path>"
    )


AAPT = '\n    xmlns:aapt="http://schemas.android.com/aapt"'


def svg(size, rounded, crop=0):
    shapes = []
    for kind, path, color, width in SHAPES:
        if kind == "fill":
            shapes.append(f'<path d="{path}" fill="{color}"/>')
        else:
            shapes.append(f'<path d="{path}" fill="none" stroke="{color}" stroke-width="{width}" stroke-linecap="round"/>')
    radius = 24 if rounded else 0
    side = 108 - 2 * crop
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="{crop} {crop} {side} {side}">'
        f'<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">'
        f'<stop offset="0" stop-color="{BG_TOP}"/><stop offset="1" stop-color="{BG_BOTTOM}"/></linearGradient></defs>'
        f'<rect x="{crop}" y="{crop}" width="{side}" height="{side}" rx="{radius}" fill="url(#bg)"/>{"".join(shapes)}</svg>'
    )


def main():
    write(RES / "drawable" / "ic_launcher_foreground.xml", vector(vector_paths()))
    write(RES / "drawable" / "ic_launcher_background.xml", vector(gradient_rect("M0,0h108v108h-108z"), extra_ns=AAPT))
    write(RES / "drawable" / "ic_launcher_monochrome.xml", vector(vector_paths("#FFFFFF", skip_shade=True)))
    # In-app mark: the 72-unit area around the safe zone, on a rounded square.
    mark = gradient_rect("M34,18h40a16,16 0 0 1 16,16v40a16,16 0 0 1 -16,16h-40a16,16 0 0 1 -16,-16v-40a16,16 0 0 1 16,-16z")
    write(RES / "drawable" / "ic_logo.xml", vector(mark + "\n" + vector_paths(), size=72, viewport=72, translate=18, extra_ns=AAPT))
    page = "<!doctype html><html><head><meta charset=\"utf-8\"><style>html,body{{margin:0;background:transparent}}</style></head><body>{}</body></html>\n"
    # Play icons are full-bleed squares (Play rounds them): crop to the area around the mark so it fills more.
    write(PLAY / "icon.html", page.format(svg(512, rounded=False, crop=16)))
    write(PLAY / "logo.svg", svg(512, rounded=True) + "\n")


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", path.relative_to(ROOT))


if __name__ == "__main__":
    main()
