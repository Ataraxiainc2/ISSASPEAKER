"""Implementation order: every feature still to build, from the simplest to the most complex.

Writes docs/features/ORDER.md from docs/features/catalog.tsv. Run it after editing the catalog:

    python tools/order.py            # rewrite docs/features/ORDER.md
    python tools/order.py --check    # fail if ORDER.md is stale (CI)

Complexity is judged by what a feature needs, not by its section: a feature that runs on the phone alone comes
before one that needs a Google permission, then background work, then an outside service, then a companion
device (watch, PC, Home Assistant), then advanced AI. Within a wave: priority first (P0 before P4), then
milestone, then id. KEYWORD_WAVES moves a feature whose needs differ from its module's.
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOG = ROOT / "docs" / "features" / "catalog.tsv"
OUTPUT = ROOT / "docs" / "features" / "ORDER.md"

WAVES = {
    1: ("Phone only", "Builds on what exists: no new permission, account or outside service."),
    2: ("One Google permission", "Needs the owner to grant one Google scope (Sheets, Calendar, Drive, Gmail, Apps Script)."),
    3: ("Background and phone integration", "Exact alarms, background work, notifications, calls, contacts, location."),
    4: ("Outside services", "Another company's API and the owner's account or key there (Spotify, Last.fm, X, news, weather, GitHub)."),
    5: ("Companion devices", "A second program or device: the Watch app, the PC companion, Home Assistant, Health Connect."),
    6: ("Advanced AI", "Agents, long-term memory, vision and adaptive behavior; built on everything above."),
}

MODULE_WAVES = {
    "PLAT": 1, "SEC": 1, "HUB": 1, "AI": 1, "CAST": 1, "ANN": 1, "VOICE": 1, "EDU": 1, "HOUSE": 1, "FIN": 1,
    "ACCT": 2, "SHEET": 2, "CAL": 2, "DRIVE": 2, "GAS": 2, "MAIL": 2, "WORK": 2,
    "RTN": 3, "PHONE": 3, "MOVE": 3,
    "SPOT": 4, "LFM": 4, "SHK": 4, "NEWS": 4, "X": 4, "BOOK": 4, "INT": 4, "DEVOPS": 4, "AUDIO": 4,
    "WEAR": 5, "HLTH": 5, "PC": 5, "DEV": 5, "HOME": 5, "SAFE": 5, "ENER": 5,
    "AGENT": 6, "MEM": 6, "VIS": 6, "EXP": 6, "USER": 6,
}

# Features whose real needs differ from their module's (matched in the English title, lower case).
KEYWORD_WAVES = [
    ("google scopes", 2),
    ("google drive", 2),
    ("token revocation", 2),
    ("battery-optimization", 3),
    ("wake-on-lan", 1),  # one UDP packet from the phone, no companion needed
    ("timer", 1),
    ("pomodoro", 1),
    ("quiet hours", 1),
    ("read any text aloud", 1),
    ("exact-time", 3),
    ("scheduled", 3),
    ("routine", 3),
    ("weather", 4),
]

PRIORITY_ORDER = {"P0": 0, "P1": 1, "P2": 2, "P3": 3, "P4": 4}


def wave_of(row):
    title = row["title_en"].lower()
    for keyword, wave in KEYWORD_WAVES:
        if keyword in title:
            return wave
    return MODULE_WAVES.get(row["module"], 6)


def render():
    lines = CATALOG.read_text(encoding="utf-8").splitlines()
    columns = lines[0].split("\t")
    rows = [dict(zip(columns, line.split("\t"))) for line in lines[1:] if line]
    pending = [r for r in rows if r["status"] != "implemented"]
    done = len(rows) - len(pending)
    pending.sort(key=lambda r: (wave_of(r), PRIORITY_ORDER[r["priority"]], int(r["milestone"][1:]), r["id"]))
    out = [
        "# Implementation order",
        "",
        "<!-- Generated by tools/order.py from docs/features/catalog.tsv. Do not edit by hand. -->",
        "",
        f"{len(pending)} features to build ({done} of {len(rows)} done), from the simplest to the most complex.",
        "Each wave needs one more kind of thing than the one before. Within a wave: priority, milestone, id.",
        "A feature that is already under way keeps going even when an earlier one is still open.",
        "",
    ]
    number = 0
    for wave, (title, why) in WAVES.items():
        items = [r for r in pending if wave_of(r) == wave]
        if not items:
            continue
        out += [f"## Wave {wave} — {title} ({len(items)})", "", why, "", "| # | Id | Feature | Module | Priority | Milestone |", "|---|---|---|---|---|---|"]
        for row in items:
            number += 1
            out.append(f"| {number} | {row['id']} | {row['title_en'].replace('|', '/')} | {row['module']} | {row['priority']} | {row['milestone']} |")
        out.append("")
    return "\n".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            sys.exit("docs/features/ORDER.md is stale: run python tools/order.py")
        print("order ok")
        return
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
