"""Writes app/src/main/assets/ai_pinned_hosts.json: the API host of every AI provider the app can reach today.

The app compares the live registry (models.dev) with this reviewed snapshot (ISP-SEC-013): a provider whose host
changed since the snapshot is not listed, and a provider newer than the snapshot needs the owner's explicit
confirmation before a key is sent to it. Run before each release and review the diff like code:

    python tools/ai/pinned_hosts.py            # download models.dev and rewrite the snapshot
    python tools/ai/pinned_hosts.py --check    # exit 1 if the snapshot file is malformed

The SDK table mirrors SdkFamilies in app/src/main/java/com/issasoda/issaspeaker/ai/AiEndpoint.kt; keep them equal.
"""
import json
import pathlib
import sys
import urllib.request
from datetime import date
from urllib.parse import urlparse

ROOT = pathlib.Path(__file__).resolve().parents[2]
TARGET = ROOT / "app" / "src" / "main" / "assets" / "ai_pinned_hosts.json"
REGISTRY_URL = "https://models.dev/api.json"
MAX_BYTES = 40_000_000

# npm package -> default API root (None: the registry must give one). Same as SdkFamilies.
SDK_DEFAULTS = {
    "@ai-sdk/openai-compatible": None,
    "@openrouter/ai-sdk-provider": None,
    "@ai-sdk/openai": "https://api.openai.com/v1",
    "@ai-sdk/google": "https://generativelanguage.googleapis.com/v1beta/openai",
    "@ai-sdk/mistral": "https://api.mistral.ai/v1",
    "@ai-sdk/xai": "https://api.x.ai/v1",
    "@ai-sdk/groq": "https://api.groq.com/openai/v1",
    "@ai-sdk/cerebras": "https://api.cerebras.ai/v1",
    "@ai-sdk/cohere": "https://api.cohere.ai/compatibility/v1",
    "@ai-sdk/anthropic": "https://api.anthropic.com/v1",
}


def host_of(provider: dict) -> str | None:
    npm = provider.get("npm")
    if npm not in SDK_DEFAULTS:
        return None
    base = (provider.get("api") or SDK_DEFAULTS[npm] or "").rstrip("/")
    if not base.startswith("https://") or "{" in base:
        return None
    return urlparse(base).hostname


def check(data: dict) -> None:
    hosts = data.get("hosts")
    if not isinstance(hosts, dict) or not hosts:
        sys.exit("ai_pinned_hosts.json: no hosts")
    for provider_id, host in hosts.items():
        if not isinstance(host, str) or not host or "/" in host or ":" in host:
            sys.exit(f"ai_pinned_hosts.json: bad host for {provider_id}: {host!r}")


def main() -> None:
    if "--check" in sys.argv:
        check(json.loads(TARGET.read_text(encoding="utf-8")))
        print(f"pinned hosts ok: {len(json.loads(TARGET.read_text(encoding='utf-8'))['hosts'])} providers")
        return
    # models.dev refuses Python's default user agent.
    request = urllib.request.Request(REGISTRY_URL, headers={"User-Agent": "ISSASPEAKER-tools (github.com/Ataraxiainc2/ISSASPEAKER)"})
    with urllib.request.urlopen(request, timeout=60) as response:
        body = response.read(MAX_BYTES + 1)
    if len(body) > MAX_BYTES:
        sys.exit("models.dev registry too large")
    registry = json.loads(body)
    hosts = {pid: h for pid, p in sorted(registry.items()) if isinstance(p, dict) and (h := host_of(p))}
    data = {
        "about": "API host of every AI provider the app can reach, reviewed at build time (ISP-SEC-013). "
                 "Generated by tools/ai/pinned_hosts.py from " + REGISTRY_URL + ".",
        "generated": date.today().isoformat(),
        "hosts": hosts,
    }
    check(data)
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(hosts)} providers")


if __name__ == "__main__":
    main()
