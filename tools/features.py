"""Feature catalog: validate docs/features/catalog.tsv and render docs/FEATURES.md from it.

The TSV is the single source of truth. FEATURES.md and the admin About screen are generated from it.
Run after every edit of the catalog:

    python tools/features.py            # validate and rewrite docs/FEATURES.md
    python tools/features.py --check    # validate and fail if docs/FEATURES.md is stale (CI)

Rules the validator enforces:
  - ids are F001, F002, ... in order, never reused or renumbered;
  - module, priority, milestone and status come from the closed lists below;
  - every original id 1..400 of the source list appears exactly once in `origin`, except the three
    the source list never assigned (259, 261, 399). A "b" suffix (242b, 320b) marks a duplicate
    entry of the source list that was kept or merged on purpose.
"""

import collections
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOG = ROOT / "docs" / "features" / "catalog.tsv"
OUTPUT = ROOT / "docs" / "FEATURES.md"

COLUMNS = ["id", "module", "priority", "milestone", "origin", "status", "title_en", "title_es", "note"]
MODULES = {
    "PLAT": "Platform",
    "SEC": "Security",
    "HUB": "Hub",
    "ACCT": "Google accounts",
    "AI": "AI engine",
    "CAST": "Google Home / Cast",
    "ANN": "Announcements",
    "RTN": "Routines and automation",
    "SHEET": "Google Sheets",
    "GAS": "Apps Script",
    "CAL": "Google Calendar",
    "MAIL": "Gmail",
    "DRIVE": "Google Drive",
    "NEWS": "News",
    "SPOT": "Spotify",
    "LFM": "Last.fm",
    "SHK": "Shikaka",
    "X": "X",
    "BOOK": "Books",
    "WEAR": "Galaxy Watch (Wear OS)",
    "HLTH": "Health Connect",
}
PRIORITIES = {
    "P0": "Foundation",
    "P1": "Core",
    "P2": "High value",
    "P3": "Advanced",
    "P4": "Experimental",
}
MILESTONES = {
    "M0": "Foundation and security baseline",
    "M1": "MVP: account, AI, speaker, birthdays, daily routine",
    "M2": "Daily announcements and routines",
    "M3": "Google productivity",
    "M4": "Music",
    "M5": "Watch and health",
    "M6": "Social and reading",
    "M7": "Advanced intelligence",
    "M8": "Experimental",
}
STATUSES = {
    "implemented": "Implemented",
    "planned": "To implement",
    "validate": "Pending: feasibility test",
    "blocked": "Pending: blocked by a decision",
}
UNASSIGNED_ORIGINS = {259, 261, 399}


def load():
    lines = CATALOG.read_text(encoding="utf-8").splitlines()
    if lines[0].split("\t") != COLUMNS:
        sys.exit(f"{CATALOG}: header must be {COLUMNS}")
    rows = []
    for number, line in enumerate(lines[1:], start=2):
        cells = line.split("\t")
        if len(cells) != len(COLUMNS):
            sys.exit(f"{CATALOG}:{number}: {len(cells)} columns, expected {len(COLUMNS)}")
        rows.append(dict(zip(COLUMNS, cells)))
    return rows


def validate(rows):
    errors = []
    origins = collections.Counter()
    for index, row in enumerate(rows, start=1):
        where = f"{row['id']}"
        if row["id"] != f"F{index:03d}":
            errors.append(f"{where}: expected id F{index:03d}")
        for column, allowed in (("module", MODULES), ("priority", PRIORITIES),
                                ("milestone", MILESTONES), ("status", STATUSES)):
            if row[column] not in allowed:
                errors.append(f"{where}: unknown {column} {row[column]!r}")
        if not row["title_en"] or not row["title_es"]:
            errors.append(f"{where}: both titles are required")
        if row["origin"] != "NEW":
            for part in row["origin"].split("+"):
                if not part.rstrip("b").isdigit():
                    errors.append(f"{where}: bad origin {part!r}")
                elif not part.endswith("b"):
                    origins[int(part)] += 1
    for original in range(1, 401):
        if original in UNASSIGNED_ORIGINS:
            continue
        if origins[original] != 1:
            errors.append(f"original #{original} appears {origins[original]} times (expected 1)")
    if errors:
        sys.exit("catalog errors:\n  " + "\n  ".join(errors))


def cell(text):
    return text.replace("|", "\\|")


def render(rows):
    by_status = collections.Counter(row["status"] for row in rows)
    by_priority = collections.Counter(row["priority"] for row in rows)
    new = sum(row["origin"] == "NEW" for row in rows)
    out = [
        "# ISSASPEAKER feature catalog",
        "",
        "<!-- Generated by tools/features.py from docs/features/catalog.tsv. Do not edit by hand. -->",
        "",
        f"**{len(rows)} features**: {len(rows) - new} from the original list of 400 (after merging",
        f"duplicates and parameter-only variants) and {new} new platform, security and reliability features.",
        "The mapping from the original numbering is in the `origin` column (`NEW` = added here).",
        "",
        "| Status | Count |",
        "|---|---|",
    ]
    out += [f"| {label} | {by_status[key]} |" for key, label in STATUSES.items()]
    out += ["", "| Priority | Count |", "|---|---|"]
    out += [f"| {key} — {label} | {by_priority[key]} |" for key, label in PRIORITIES.items()]
    for milestone, title in MILESTONES.items():
        group = [row for row in rows if row["milestone"] == milestone]
        if not group:
            continue
        out += ["", f"## {milestone} — {title} ({len(group)})", "",
                "| ID | Module | P | Feature | Característica | Origin | Status | Note |",
                "|---|---|---|---|---|---|---|---|"]
        for row in group:
            out.append(
                f"| {row['id']} | {row['module']} | {row['priority']} | {cell(row['title_en'])} | "
                f"{cell(row['title_es'])} | {row['origin']} | {STATUSES[row['status']]} | {cell(row['note'])} |"
            )
    return "\n".join(out) + "\n"


def main():
    rows = load()
    validate(rows)
    text = render(rows)
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            sys.exit("docs/FEATURES.md is stale: run python tools/features.py")
        print(f"catalog ok: {len(rows)} features")
        return
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(rows)} features")


if __name__ == "__main__":
    main()
